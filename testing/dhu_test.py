#!/usr/bin/env python3
"""Repeatable Android Auto DHU captures; Python standard library only.

No adb commands, phone settings writes, or ~/.android configuration writes.
Successful capture is evidence to review, never an automatic UI/scaling pass.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import math
import os
from pathlib import Path
import struct
import subprocess
import sys
import threading
import time


ROOT = Path(__file__).resolve().parent
PROFILES = {
    "480p160": {"resolution": "800x480", "dpi": 160},
    "720p160": {"resolution": "1280x720", "dpi": 160},
    "720p240": {"resolution": "1280x720", "dpi": 240},
    "720p320": {"resolution": "1280x720", "dpi": 320},
    "1080p240": {"resolution": "1920x1080", "dpi": 240},
    "1080p320": {"resolution": "1920x1080", "dpi": 320},
    "ultrawide1280x500-dpi160": {
        "resolution": "1280x720", "dpi": 160, "marginheight": 220,
    },
}
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def profile_text(profile: dict) -> str:
    lines = [
        "# Generated by dhu_test.py. Explicit per-run config; no home config edits.",
        "[general]", "touch = true", "touchpad = false", "controller = false",
        "instrumentcluster = false", "normalizedpi = false", "framerate = 30",
    ]
    lines.extend(f"{key} = {value}" for key, value in profile.items())
    # DPI is the requested logical density. Leave realdpi at DHU's documented
    # default so the DPI comparison changes just one parameter.
    lines.extend(["", "[sensors]", "night_mode = true", "driving_status = true", ""])
    return "\n".join(lines)


def prepare() -> list[Path]:
    folder = ROOT / "profiles"
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, profile in PROFILES.items():
        path = folder / f"{name}.ini"
        path.write_text(profile_text(profile), encoding="utf-8")
        paths.append(path)
    return paths


def locate_dhu(explicit: str | None) -> Path:
    if explicit:
        path = Path(explicit).expanduser().resolve()
        if not path.is_file():
            raise ValueError(f"DHU does not exist: {path}")
        return path
    candidates = [ROOT.parent / "android-sdk/extras/google/auto/desktop-head-unit",
                  ROOT.parent / "source/android-sdk/extras/google/auto/desktop-head-unit"]
    for env_name in ("ANDROID_SDK_ROOT", "ANDROID_HOME"):
        if os.environ.get(env_name):
            candidates.append(Path(os.environ[env_name]) / "extras/google/auto/desktop-head-unit")
    for path in candidates:
        if path.is_file():
            return path.resolve()
    raise ValueError("DHU not found. Pass --dhu /absolute/path/to/desktop-head-unit")


def png_metadata(path: Path) -> dict | None:
    try:
        data = path.read_bytes()
        # The IEND chunk verifies a completed PNG, rather than a file still being
        # written. PNG decoding and visual correctness remain separate checks.
        if len(data) < 45 or not data.startswith(PNG_SIGNATURE) or data[-8:-4] != b"IEND":
            return None
        width, height = struct.unpack(">II", data[16:24])
        if not width or not height:
            return None
        return {"file": path.name, "width": width, "height": height,
                "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    except OSError:
        return None


class Session:
    def __init__(self, command: list[str], folder: Path):
        self.command = command
        self.folder = folder
        self.proc: subprocess.Popen | None = None
        self.threads: list[threading.Thread] = []
        self.commands: list[dict] = []

    def start(self):
        self.proc = subprocess.Popen(
            self.command, cwd=self.folder, stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        )
        for name, stream in (("stdout", self.proc.stdout), ("stderr", self.proc.stderr)):
            def drain(source=stream, destination=self.folder / f"{name}.log"):
                with destination.open("wb") as log:
                    while True:
                        chunk = os.read(source.fileno(), 65536)
                        if not chunk:
                            break
                        log.write(chunk)
                        log.flush()
            thread = threading.Thread(target=drain, daemon=True)
            thread.start()
            self.threads.append(thread)

    def send(self, command: str):
        if self.proc is None or self.proc.poll() is not None:
            raise RuntimeError("DHU exited before the capture sequence completed")
        if "\n" in command or "\r" in command:
            raise ValueError("Console commands must be single lines")
        self.commands.append({"utc": dt.datetime.now(dt.timezone.utc).isoformat(), "command": command})
        self.proc.stdin.write((command + "\n").encode("utf-8"))
        self.proc.stdin.flush()

    def pause(self, seconds: float):
        until = time.monotonic() + seconds
        while time.monotonic() < until:
            if self.proc.poll() is not None:
                raise RuntimeError("DHU exited while waiting for the UI")
            time.sleep(min(0.2, max(0, until - time.monotonic())))

    def capture(self, name: str, timeout: float, repeat: bool = False) -> dict:
        path = self.folder / name
        deadline = time.monotonic() + timeout
        next_request = 0.0
        while time.monotonic() < deadline:
            found = png_metadata(path)
            if found:
                return found
            now = time.monotonic()
            if now >= next_request:
                self.send(f"screenshot {name}")
                next_request = now + (3 if repeat else timeout + 1)
            self.pause(0.2)
        raise TimeoutError(f"No completed {name} within {timeout:g} seconds")

    def stop(self) -> dict:
        details = {"forced_termination": False}
        if self.proc is None:
            return details
        if self.proc.poll() is None:
            try:
                self.send("quit")
                self.proc.wait(timeout=5)
            except (BrokenPipeError, RuntimeError, subprocess.TimeoutExpired):
                details["forced_termination"] = True
                self.proc.terminate()
                try:
                    self.proc.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    self.proc.kill()
                    self.proc.wait(timeout=3)
        for thread in self.threads:
            thread.join(timeout=2)
        details["exit_code"] = self.proc.returncode
        return details


def run(args) -> int:
    prepare()
    dhu = locate_dhu(args.dhu)
    profile_path = ROOT / "profiles" / f"{args.profile}.ini"
    command = [str(dhu), f"--adb={args.port}", "-c", str(profile_path)]
    if args.headless:
        command.append("--headless")
    plan = {
        "profile": args.profile,
        "profile_values": PROFILES[args.profile],
        "command": command,
        "label": args.label,
        "note": args.note,
        "startup_timeout_seconds": args.startup_timeout,
        "settle_seconds": args.settle,
        "screenshots": ["00-startup.png", "01-home-day.png", "02-navigation-day.png",
                        "03-navigation-night.png", "04-home-night.png"],
        "writes_phone_settings": False,
        "prerequisite": "AA head unit server already running; adb forward tcp:PORT tcp:5277; unlocked phone",
        "assessment": "Captures require visual review; a high-DPI failure is a recorded result, not a scaling pass.",
    }
    if args.dry_run:
        print(json.dumps(plan, indent=2))
        return 0
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    folder = Path(args.runs).expanduser().resolve() / f"{stamp}-{args.profile}"
    folder.mkdir(parents=True, exist_ok=False)
    # Run from a snapshot so a later prepare/config edit cannot alter its evidence.
    config_snapshot = folder / "profile.ini"
    config_snapshot.write_bytes(profile_path.read_bytes())
    command[command.index("-c") + 1] = str(config_snapshot)
    plan["command"] = command
    manifest = {**plan, "started_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
                "status": "starting", "visual_review": "pending", "captures": []}
    manifest_path = folder / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    session = Session(command, folder)
    result = 1
    print(f"Run folder: {folder}", flush=True)
    try:
        version = subprocess.run([str(dhu), "--version"], capture_output=True, text=True, timeout=10)
        (folder / "dhu-version.txt").write_text(version.stdout + version.stderr, encoding="utf-8")
        session.start()
        manifest["captures"].append(session.capture("00-startup.png", args.startup_timeout, repeat=True))
        print("Projection frame received; collecting home/navigation day/night captures.", flush=True)
        for commands, filename in [
            (["day", "keycode home"], "01-home-day.png"),
            (["keycode navigation"], "02-navigation-day.png"),
            (["night"], "03-navigation-night.png"),
            (["keycode home"], "04-home-night.png"),
        ]:
            for command_text in commands:
                session.send(command_text)
            session.pause(args.settle)
            manifest["captures"].append(session.capture(filename, args.capture_timeout))
        session.send("day")
        if args.interactive:
            print("Interactive DHU console. Enter screenshot NAME.png, tap X Y, or quit. Ctrl-D ends.", flush=True)
            while True:
                try:
                    line = input("dhu> ").strip()
                except EOFError:
                    break
                if line in {"quit", "exit"}:
                    break
                if line:
                    session.send(line)
        manifest["status"] = "captured-awaiting-review"
        result = 0
    except KeyboardInterrupt:
        manifest["status"] = "interrupted"
        manifest["failure"] = "Operator interrupted the run"
        result = 130
    except (OSError, RuntimeError, TimeoutError, subprocess.SubprocessError) as error:
        manifest["status"] = "capture-failed"
        manifest["failure"] = f"{type(error).__name__}: {error}"
        print(manifest["failure"], file=sys.stderr)
    finally:
        manifest["process"] = session.stop()
        process_problem = (manifest["process"].get("forced_termination")
                           or manifest["process"].get("exit_code") not in {None, 0})
        if manifest["status"] == "captured-awaiting-review" and process_problem:
            manifest["status"] = "capture-failed"
            manifest["failure"] = "PNG frames arrived, but DHU exited abnormally or required termination"
            result = 1
        manifest["commands"] = session.commands
        # Include manual screenshots without assuming their screen contents.
        manifest["all_png_files"] = [info for path in sorted(folder.glob("*.png"))
                                     if (info := png_metadata(path))]
        manifest["ended_utc"] = dt.datetime.now(dt.timezone.utc).isoformat()
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Result: {manifest['status']}; see {manifest_path}", flush=True)
    return result


def positive_float(value: str) -> float:
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise argparse.ArgumentTypeError("must be finite and positive")
    return number


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser("prepare", help="write explicit reusable INI profiles")
    sub.add_parser("list", help="list available profiles without launching DHU")
    command = sub.add_parser("run", help="capture one profile; prerequisites must already be ready")
    command.add_argument("profile", choices=PROFILES)
    command.add_argument("--dhu", help="DHU executable; defaults to sibling workspace android-sdk")
    command.add_argument("--port", type=int, default=5277, help="local forwarded ADB-tunnel port")
    command.add_argument("--runs", default=str(ROOT / "runs"), help="run evidence directory")
    command.add_argument("--label", default="unlabeled", help="for example before, after, rollback, reconnect")
    command.add_argument("--note", default="", help="settings/build/firmware context for later comparison")
    command.add_argument("--startup-timeout", type=positive_float, default=45)
    command.add_argument("--capture-timeout", type=positive_float, default=15)
    command.add_argument("--settle", type=positive_float, default=4)
    command.add_argument("--headless", action="store_true", help="optional DHU no-window mode")
    command.add_argument("--interactive", action="store_true", help="keep console available after captures")
    command.add_argument("--dry-run", action="store_true", help="prepare profiles and print plan; do not launch DHU")
    args = parser.parse_args()
    try:
        if args.action == "prepare":
            for path in prepare():
                print(path)
            return 0
        if args.action == "list":
            for name, profile in PROFILES.items():
                print(f"{name:30s} {json.dumps(profile, sort_keys=True)}")
            return 0
        if not 1 <= args.port <= 65535:
            parser.error("--port must be between 1 and 65535")
        return run(args)
    except (ValueError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
